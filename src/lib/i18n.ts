function fill(template: string, vars?: Vars): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? ""));
}

export function translate(language: Language, text: string, vars?: Vars): string {
  const source = legacy[text] ?? text;
  if (vars || language !== "ko") {
    const template = language === "ko" ? (ko[source] ?? source) : source;
    return fill(template, vars);
  }
  if (ko[source]) return ko[source];
  for (const item of patterns) {
    const match = source.match(item.pattern);
    if (!match || !ko[item.key]) continue;
    const captured: Vars = {};
    item.names.forEach((name, index) => {
      captured[name] = match[index + 1] ?? "";
    });
    return fill(ko[item.key], captured);
  }
  return source;
}

export function localizeTitle(language: Language, title: string): string {
  if (title === "New chat" || title === "새 작업" || title === "새 채팅" || title === "New task") {
    return translate(language, "New chat");
  }
  return title;
}

export function wasDenied(content: string): boolean {
  return /denied/i.test(content) || content.includes("거부");
}

export function useT() {
  const language = useUi((state) => state.language);
  return (text: string, vars?: Vars) => translate(language, text, vars);
}
